   ppObj.glareShapeGhostDistortion = math.lerp(glareShapeGhostDistortionStart,glareShapeGhostDistortionEnd,normalisedCBEcrossover)

   ppObj.glareShapeGhostSharpeness = math.lerp(glareShapeGhostSharpenessStart,glareShapeGhostSharpenessEnd,normalisedCBEcrossover)

   ppObj.glareShapeAfterimageLength = glareShapeAfterimageLength

   ppObj.glareShapeStarStreaks = glareShapeStarStreaks

   if(glareAnamorphic == 1) then
    ppObj.glareAnamorphic = true
   else
    ppObj.glareAnamorphic = false
   end
   dashcam = pure.script.ui.getValue("Dashcam mode")
    if(dashcam) then
        ppObj.lensDistortionEnabled = true
    else
        ppObj.lensDistortionEnabled= false
    end
   --ac.debug("glareAnamorphic",params.glareAnamorphic)
    impactVis = pure.script.ui.getValue("Impact Vision")
    if(impactVis) then

        local ImpactVisionBoost =pure.script.ui.getValue("Crash effect strength multiplier")
        local dofIntensityAdjust = pure.script.ui.getValue("Maximum speed blur intensity adjustment")
        local adjustedFastFocus = fastFocus        
        local dofMaxLevel = math.clamp(highDof + ( -lowDOf * math.pow(dofIntensityAdjust,3)),4,64)
        --ac.debug("dofMaxLevel",dofMaxLevel)
        local chaseDof = pure.script.ui.getValue("Chase cam DOF")

        if dofIntensityAdjust == -1 then
            adjustedFastFocus = fastFocus/2
        end
        if sim==null then
            sim = ac.getSim()
        end
        if(C13_CheckCamera()) then
            ImpactVisionDT = ac.getGameDeltaT()
            
            car = ac.getCar(sim.focusedCar)
            
            --G = C13_Smooth(G,car.acceleration,0.1)
            G = math.applyLag(G,car.acceleration,0.1,ImpactVisionDT)
            scalarG = math.applyLag(scalarG,(math.saturateN(math.min((G:length()-1)/2,1))),0.05,ImpactVisionDT) 
            nHit = C13_Hit(G:length())
            local gforceUp = math.abs(G.y)/3
            local gforceFront = -(G.z)/10
            local gforceFlight = math.saturateN(-(G.z)/10)
            local brakeDofReduction = math.saturateN(-(G.z)-0.3) * car.brake
            local rpmLimiter = 10000
            if(car.rpmLimiter ~= nil) then
                rpmLimiter = car.rpmLimiter
            end
            local RPMboost = math.lerp(math.pow(math.saturateN(car.rpm/rpmLimiter),5)/3,0,normDofMax)
            --ac.debug("RPMboost",RPMboost)
            
            --scalarG = math.min(scalarG,1)
            
     
            


            local speedDOFend = pure.script.ui.getValue("High speed limit km/h")
            --ac.debug("speedDOFend",speedDOFend)
            local speedDOFstart = pure.script.ui.getValue("Low speed limit km/h")
            --ac.debug("speedDOFstart",speedDOFstart)
            noDofShelf = speedDOFstart
            --ac.debug("nHit",nHit)
            Gy = math.applyLag(Gy,G.y,0.2,ImpactVisionDT)
            speedLast = math.max(math.applyLag(speedLast, car.speedKmh-speedDOFstart, 0.15, ImpactVisionDT),0)
            --ac.debug("speedlast",speedLast)
            --ac.debug("speed",car.speedKmh)
            
            --ac.debug("cockpit",cockpit)

           
            normDofMax =  math.applyLag(normDofMax, math.min(math.max((speedLast)/(speedDOFend-speedDOFstart),0),1), 0.3, ImpactVisionDT)
            --ac.debug("normDofMax",normDofMax)

            if(sim.cameraMode == ac.CameraMode.Cockpit or chaseDof) then
                --ac.debug("normDofMax",normDofMax)
                ppObj.dofActive = true
                ppObj.dofFocusDistance= math.lerp(math.lerp(slowFocus,adjustedFastFocus,normDofMax),slowFocus,math.min(nHit,1))
                ppObj.dofApertureFNumber= math.clamp(
                                                    math.lerp(
                                                                math.lerp(
                                                                    lowDOf,dofMaxLevel,
                                                                    normDofMax - brakeDofReduction/2),
                                                                    dofMaxLevel-3,math.min(math.pow(nHit,0.4) + math.saturateN(math.abs(G.x))/2,
                                                                    1
                                                                )
                                                            ),
                                                    4,64)
            end

                    --chromaticAberrationEnabled boolean
