   ppObj.glareShapeStarLuminance =callbackStarLum

   callbackStarSoftness= math.lerp(glareStarSoftnessStart,glareStarSoftnessEnd,normalisedCBEcrossover)
   ppObj.glareStarSoftness =callbackStarSoftness

   ppObj.glareBloomLuminanceGamma = math.lerp(glareBloomGammaStart,glareBloomGammaEnd,normalisedCBEcrossover)

   ppObj.glareBrightPass = glarebrightPass

   ppObj.glareShapeStarLength = math.lerp(glareShapeStarLengthStart,glareShapeStarLengthEnd,normalisedCBEcrossover)

   ppObj.glareShapeStarSecondaryLength = math.lerp(glareShapeStarSecondaryLengthStart,glareShapeStarSecondaryLengthEnd,normalisedCBEcrossover)

  

