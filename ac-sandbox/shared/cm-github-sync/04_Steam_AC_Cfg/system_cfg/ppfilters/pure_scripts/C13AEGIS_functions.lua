                    --ac.debug("expTimeout",expTimeout)
                end
        
        elseif math.abs(oldExposure-newExposure) < 0.01 then
            expTimeout = math.applyLag(expTimeout, 0.3,0.9,dt)
            if(expTimeout > 0.299) then
              changing = false
            end
        
        elseif changing then
            if newExposure > oldExposure then
                oldExposure = math.applyLag(oldExposure,newExposure,0.8,dt)
            else
                oldExposure = math.applyLag(oldExposure,newExposure,0.7,dt)
            end
        else
            changing = true
          --[[  if newExposure > oldExposure then
