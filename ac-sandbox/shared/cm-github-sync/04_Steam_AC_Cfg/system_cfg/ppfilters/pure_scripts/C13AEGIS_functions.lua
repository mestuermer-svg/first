    return finalFog * fogBoost

end

function C13_BellCurve(x, midpoint, width)
    local coefficient = 1 / math.sqrt(2 * math.pi * 0.16)
    local exponent = -((x - midpoint)^2) / (2 * width^2)
    return coefficient * math.exp(exponent)
end


