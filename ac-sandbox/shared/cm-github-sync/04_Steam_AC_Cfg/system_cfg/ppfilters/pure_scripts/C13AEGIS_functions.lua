function C13_setFogColor()

    morningFog = math.lerp(fogColorMorning2,fogColorMorning, math.saturateN(fog*5))
    --ac.debug("lcs",pure.system.isCSPGammaFix())
    if pure.system.isCSPGammaFix() then
        mistFogMidday = math.lerp(fogColorMidday2,fogColorMidday,math.pow(fog,0.5))
        finalFog = pure.mod.dayCurve(morningFog,mistFogMidday,1)
    else
        finalFog = pure.mod.dayCurve(morningFog,fogColorMidday,1)
    end
    
    --finalFog = math.lerp(finalFog,math.lerp(fogColorRain,fogColor,1-pure.mod.sun(0)),pure.world.getSunCover())
    finalFog = math.lerp(finalFog,math.lerp(fogColorRain,fogColor,1-pure.mod.sun(0)),math.pow(rainIntensity,0.2))
    
    mistBoost = 1 + 5 * C13_BellCurve(fog,0.5,0.125)
    --ac.debug("mistBoost",mistBoost)
    local fogColorMistAdapted = fogColorMist * (1 - 0.7 * math.pow(fog,1/2))
    finalFog = math.lerp(finalFog,math.lerp(fogColorMistAdapted*mistBoost,fogColor,1-pure.mod.sun(0)),(pure.mod.dayCurve(fog*0.8,fog)))
    finalFog = math.lerp(finalFog,fogColor,(1-pure.mod.twilight(0)))

    RGBToHSV_To(finalFogHsv,finalFog)
    finalFogHsv.v = math.clamp(finalFogHsv.v,0,math.clamp(20-15*pure.world.getCloudCoverage() - 13 * (math.saturateN(fog-0.6)/0.4),4,20))
    finalFogHsv.v = finalFogHsv.v * pure.script.weather.getVariable("fogWeatherBrightness")
    --ac.debug("fogWeatherBrightness",pure.script.weather.getVariable("fogWeatherBrightness"))
    --ac.debug("cloudCoverage",pure.world.getCloudCoverage())
    if pure.system.isCSPGammaFix() then
        finalFogHsv.s = math.clamp(finalFogHsv.s,0,0.9-0.3*pure.world.getCloudCoverage())
    else
    finalFogHsv.s = math.clamp(finalFogHsv.s,0,0.6-0.3*pure.world.getCloudCoverage())
    end
    HSVToRGB_To(finalFog,finalFogHsv.h,finalFogHsv.s,finalFogHsv.v)

    finalFog = finalFog * 1 + 0.05 * __PURE__fog_get_cam_position_NLP() * pure.mod.night(0)
   
    --finalFog = math.lerp(finalFog,fogColor,pure.mod.nightCurve(1,1))
